CREATE TABLE IF NOT EXISTS websites (
  domain TEXT PRIMARY KEY,
  platform TEXT NOT NULL,
  latest_crawl_id TEXT NOT NULL,
  settings_json TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS crawls (
  crawl_id TEXT PRIMARY KEY,
  domain TEXT NOT NULL,
  platform TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT,
  budget_json TEXT NOT NULL,
  status TEXT NOT NULL,
  max_level TEXT NOT NULL,
  coverage_json TEXT NOT NULL,
  robots_txt_raw TEXT,
  crawl_delay_ms INTEGER NOT NULL DEFAULT 250
);

CREATE TABLE IF NOT EXISTS html_snapshots (
  crawl_id TEXT NOT NULL,
  normalized_url TEXT NOT NULL,
  compressed_html BYTEA NOT NULL,
  extracted_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  PRIMARY KEY (crawl_id, normalized_url)
);

